#!/usr/bin/env python3
"""Write gtcrn_weights.h from the upstream GTCRN checkpoint.

Usage: export_weights.py <gtcrn-repo> > gtcrn_weights.h

<gtcrn-repo> is a clone of https://github.com/Xiaobin-Rong/gtcrn (needs torch).
The checkpoint is stream/onnx_models/model_trained_on_dns3.tar, the source of
the official stream/onnx_models/gtcrn_simple.onnx, converted to the streaming
model. BatchNorm is folded into the conv before it. The ERB matrices are not
exported: gtcrn.c computes them.
"""
import hashlib
import importlib.util
import os
import sys

import numpy as np
import torch

repo = sys.argv[1]
sys.path.insert(0, os.path.join(repo, "stream"))
from gtcrn_stream import StreamGTCRN  # noqa: E402
from modules.convert import convert_to_stream  # noqa: E402

spec = importlib.util.spec_from_file_location("gtcrn_offline", os.path.join(repo, "gtcrn.py"))
offline = importlib.util.module_from_spec(spec)
spec.loader.exec_module(offline)

ckpt = os.path.join(repo, "stream", "onnx_models", "model_trained_on_dns3.tar")
model = offline.GTCRN().eval()
model.load_state_dict(torch.load(ckpt, map_location="cpu", weights_only=False)["model"])
stream = StreamGTCRN().eval()
convert_to_stream(stream, model)
sd = {k: v.detach().numpy().astype(np.float64) for k, v in stream.state_dict().items()}

out = []


def emit(name, a):
    a = np.asarray(a, dtype=np.float32).ravel()
    vals = ["%.9gf" % v for v in a]
    lines = [", ".join(vals[i:i + 8]) for i in range(0, len(vals), 8)]
    out.append("static const float %s[%d] = {\n    %s,\n};\n" % (name, len(a), ",\n    ".join(lines)))


def bn_scale(p):
    s = sd[p + ".weight"] / np.sqrt(sd[p + ".running_var"] + 1e-5)
    return s, sd[p + ".bias"] - sd[p + ".running_mean"] * s


def conv(name, w, b, bn, out_axis):
    """w in canonical layout, out_axis = axis of the output channel."""
    s, t = bn_scale(bn)
    shape = [1] * w.ndim
    shape[out_axis] = -1
    emit(name + "_w", w * s.reshape(shape))
    emit(name + "_b", b * s + t)


def gru(name, p, suffix=""):
    for k in ("weight_ih", "weight_hh", "bias_ih", "bias_hh"):
        emit("%s_%s" % (name, k.replace("weight_", "w").replace("bias_", "b")), sd["%s.%s_l0%s" % (p, k, suffix)])


# Encoder ConvBlocks: Conv2d (out, in, 1, 5) -> [out][in][5].
for i in range(2):
    p = "encoder.en_convs.%d" % i
    conv("en%d" % i, sd[p + ".conv.weight"][:, :, 0, :], sd[p + ".conv.bias"], p + ".bn", 0)
    emit("en%d_a" % i, sd[p + ".act.weight"])

# GTConv blocks: 0..2 encoder, 3..5 decoder. Canonical 1x1 conv is [out][in].
for g in range(6):
    p = "encoder.en_convs.%d" % (g + 2) if g < 3 else "decoder.de_convs.%d" % (g - 3)
    dc = "Conv2d" if g < 3 else "ConvTranspose2d"
    w1 = sd[p + ".point_conv1.weight"][:, :, 0, 0]
    w2 = sd[p + ".point_conv2.weight"][:, :, 0, 0]
    if g >= 3:
        w1, w2 = w1.T, w2.T
    conv("gt%d_pc1" % g, w1, sd[p + ".point_conv1.bias"], p + ".point_bn1", 0)
    emit("gt%d_a1" % g, sd[p + ".point_act.weight"])
    conv("gt%d_dc" % g, sd["%s.depth_conv.%s.weight" % (p, dc)][:, 0], sd["%s.depth_conv.%s.bias" % (p, dc)],
         p + ".depth_bn", 0)
    emit("gt%d_a2" % g, sd[p + ".depth_act.weight"])
    conv("gt%d_pc2" % g, w2, sd[p + ".point_conv2.bias"], p + ".point_bn2", 0)
    gru("gt%d_tra" % g, p + ".tra.att_gru")
    emit("gt%d_tra_fcw" % g, sd[p + ".tra.att_fc.weight"])
    emit("gt%d_tra_fcb" % g, sd[p + ".tra.att_fc.bias"])

for d in range(2):
    p = "dpgrnn%d" % (d + 1)
    for r in (1, 2):
        gru("dp%d_intra%d_f" % (d, r), "%s.intra_rnn.rnn%d" % (p, r))
        gru("dp%d_intra%d_b" % (d, r), "%s.intra_rnn.rnn%d" % (p, r), "_reverse")
        gru("dp%d_inter%d" % (d, r), "%s.inter_rnn.rnn%d" % (p, r))
    for part in ("intra", "inter"):
        emit("dp%d_%s_fcw" % (d, part), sd["%s.%s_fc.weight" % (p, part)])
        emit("dp%d_%s_fcb" % (d, part), sd["%s.%s_fc.bias" % (p, part)])
        emit("dp%d_%s_lnw" % (d, part), sd["%s.%s_ln.weight" % (p, part)])
        emit("dp%d_%s_lnb" % (d, part), sd["%s.%s_ln.bias" % (p, part)])

# Decoder ConvBlocks: ConvTranspose2d (in, out/groups, 1, 5) -> [in][out/groups][5].
for i, groups in ((3, 2), (4, 1)):
    p = "decoder.de_convs.%d" % i
    w = sd[p + ".conv.weight"][:, :, 0, :]
    s, t = bn_scale(p + ".bn")
    n_in, n_out_g = w.shape[0], w.shape[1]
    for c in range(n_in):
        g = c // (n_in // groups)
        w[c] *= s[g * n_out_g:(g + 1) * n_out_g, None]
    emit("de%d_w" % (i - 3), w)
    emit("de%d_b" % (i - 3), sd[p + ".conv.bias"] * s + t)
    if i == 3:
        emit("de0_a", sd[p + ".act.weight"])

digest = hashlib.sha256(open(ckpt, "rb").read()).hexdigest()
print("/* Generated by export_weights.py from GTCRN stream/onnx_models/model_trained_on_dns3.tar")
print(" * (sha256 %s), MIT license, see LICENSE. Do not edit. */" % digest)
print("/* clang-format off */")
print("\n".join(out), end="")
